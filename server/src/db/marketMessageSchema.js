export const MARKET_MESSAGE_SCHEMA_SQL = `
  CREATE TABLE IF NOT EXISTS market_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id VARCHAR(100) NOT NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    parent_id BIGINT REFERENCES market_messages(id) ON DELETE CASCADE,
    username VARCHAR(80) NOT NULL CHECK (char_length(btrim(username)) > 0),
    message TEXT NOT NULL CHECK (char_length(btrim(message)) BETWEEN 1 AND 500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

  ALTER TABLE market_messages
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id) ON DELETE SET NULL;
  ALTER TABLE market_messages
    ADD COLUMN IF NOT EXISTS parent_id BIGINT REFERENCES market_messages(id) ON DELETE CASCADE;

  CREATE INDEX IF NOT EXISTS market_messages_market_created_idx
    ON market_messages (market_id, created_at DESC, id DESC);
  CREATE INDEX IF NOT EXISTS market_messages_parent_created_idx
    ON market_messages (parent_id, created_at, id)
    WHERE parent_id IS NOT NULL;

  CREATE TABLE IF NOT EXISTS market_message_reactions (
    message_id BIGINT NOT NULL REFERENCES market_messages(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reaction VARCHAR(20) NOT NULL DEFAULT 'like'
      CHECK (reaction IN ('like', 'love', 'care', 'haha', 'wow', 'sad', 'angry')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (message_id, user_id)
  );

  DO $$
  BEGIN
    IF EXISTS (
      SELECT 1 FROM pg_constraint
      WHERE conrelid = 'market_message_reactions'::regclass
        AND conname = 'market_message_reactions_reaction_check'
        AND pg_get_constraintdef(oid) NOT LIKE '%care%'
    ) THEN
      ALTER TABLE market_message_reactions
        DROP CONSTRAINT market_message_reactions_reaction_check;
    END IF;

    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint
      WHERE conrelid = 'market_message_reactions'::regclass
        AND conname = 'market_message_reactions_reaction_check'
    ) THEN
      ALTER TABLE market_message_reactions
        ADD CONSTRAINT market_message_reactions_reaction_check
        CHECK (reaction IN ('like', 'love', 'care', 'haha', 'wow', 'sad', 'angry'));
    END IF;
  END $$;
`;

export async function initializeMarketMessageDatabase(database) {
  await database.query(MARKET_MESSAGE_SCHEMA_SQL);
}
