// Bakong Open API payment schema shared by startup and the migrate script.
export const BAKONG_SCHEMA_SQL = `
  CREATE TABLE IF NOT EXISTS bakong_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tran_id VARCHAR(25) NOT NULL UNIQUE,
    md5 CHAR(32) NOT NULL UNIQUE,
    qr_string TEXT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(100),
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'USD'
      CHECK (currency IN ('USD', 'KHR')),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
      CHECK (status IN ('PENDING', 'PAID', 'EXPIRED', 'FAILED')),
    status_access_token_hash CHAR(64)
      CHECK (
        status_access_token_hash IS NULL
        OR status_access_token_hash ~ '^[a-f0-9]{64}$'
      ),
    expires_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    provider_evidence JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

  CREATE INDEX IF NOT EXISTS idx_bakong_payments_status_expires
    ON bakong_payments (status, expires_at);
`

// Create the Bakong payment table when it is missing.
export async function initializeBakongDatabase(db) {
  await db.query(BAKONG_SCHEMA_SQL)
}
