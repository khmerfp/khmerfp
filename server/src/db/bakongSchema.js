// Bakong Open API payment schema shared by startup and the migrate script.
export const BAKONG_SCHEMA_SQL = `
  CREATE TABLE IF NOT EXISTS bakong_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    tran_id VARCHAR(25) NOT NULL UNIQUE,
    md5 CHAR(32) NOT NULL UNIQUE,
    qr_string TEXT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(100),
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    amount_minor BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'USD'
      CHECK (currency IN ('USD', 'KHR')),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
      CHECK (status IN ('PENDING', 'PAID', 'EXPIRED', 'FAILED')),
    status_access_token_hash CHAR(64)
      CHECK (
        status_access_token_hash IS NULL
        OR status_access_token_hash ~ '^[a-f0-9]{64}$'
      ),
    idempotency_key VARCHAR(64),
    expires_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    wallet_credited_at TIMESTAMPTZ,
    provider_evidence JSONB,
    last_checked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

  ALTER TABLE bakong_payments
    ADD COLUMN IF NOT EXISTS user_id BIGINT
      REFERENCES users(id) ON DELETE SET NULL;
  ALTER TABLE bakong_payments
    ADD COLUMN IF NOT EXISTS amount_minor BIGINT;
  ALTER TABLE bakong_payments
    ADD COLUMN IF NOT EXISTS idempotency_key VARCHAR(64);
  ALTER TABLE bakong_payments
    ADD COLUMN IF NOT EXISTS wallet_credited_at TIMESTAMPTZ;
  ALTER TABLE bakong_payments
    ADD COLUMN IF NOT EXISTS last_checked_at TIMESTAMPTZ;

  -- Backfill rows created before amount_minor existed.
  UPDATE bakong_payments
     SET amount_minor = CASE
       WHEN currency = 'KHR' THEN ROUND(amount)::BIGINT
       ELSE ROUND(amount * 100)::BIGINT
     END
   WHERE amount_minor IS NULL;

  ALTER TABLE bakong_payments ALTER COLUMN amount_minor SET NOT NULL;

  DO $$
  BEGIN
    ALTER TABLE bakong_payments
      ADD CONSTRAINT bakong_payments_amount_minor_positive
      CHECK (amount_minor > 0);
  EXCEPTION WHEN duplicate_object THEN NULL;
  END $$;

  -- Older server deployments insert without amount_minor. Fill it before the
  -- NOT NULL and CHECK constraints run so both code versions can coexist.
  CREATE OR REPLACE FUNCTION bakong_payments_fill_amount_minor()
  RETURNS TRIGGER AS $$
  BEGIN
    IF NEW.amount_minor IS NULL THEN
      NEW.amount_minor := CASE
        WHEN NEW.currency = 'KHR' THEN ROUND(NEW.amount)::BIGINT
        ELSE ROUND(NEW.amount * 100)::BIGINT
      END;
    END IF;

    RETURN NEW;
  END;
  $$ LANGUAGE plpgsql;

  DROP TRIGGER IF EXISTS bakong_payments_fill_amount_minor
    ON bakong_payments;

  CREATE TRIGGER bakong_payments_fill_amount_minor
    BEFORE INSERT ON bakong_payments
    FOR EACH ROW
    EXECUTE FUNCTION bakong_payments_fill_amount_minor();

  CREATE INDEX IF NOT EXISTS idx_bakong_payments_status_expires
    ON bakong_payments (status, expires_at);

  CREATE UNIQUE INDEX IF NOT EXISTS idx_bakong_payments_user_idempotency
    ON bakong_payments (user_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;

  CREATE INDEX IF NOT EXISTS idx_bakong_payments_user_status
    ON bakong_payments (user_id, status);
`

// Create the Bakong payment table when it is missing.
export async function initializeBakongDatabase(db) {
  await db.query(BAKONG_SCHEMA_SQL)
}
