import pg from 'pg'
import { initializeAuthDatabase } from '../db/authSchema.js'

const { Pool } = pg

export const DATABASE_CONNECTION_TIMEOUT_MS = 15000

let pool = null

// Connect to the configured PostgreSQL database
export async function connectToDatabase(uri, options = {}) {
  if (typeof uri !== 'string' || uri.trim() === '') {
    throw new Error('DATABASE_URL is required.')
  }

  if (pool) {
    return pool
  }

  const newPool = new Pool({
    connectionString: uri,
    connectionTimeoutMillis: DATABASE_CONNECTION_TIMEOUT_MS,
    ...options,
  })

  newPool.on('error', () => {
    console.error(
      'PostgreSQL connection error; connection details have been redacted.'
    )
  })

  try {
    await newPool.query('SELECT 1')
    pool = newPool

    console.info('PostgreSQL connected successfully.')

    return pool
  } catch (error) {
    await newPool.end()
    throw error
  }
}

// Get the PostgreSQL connection pool
export function getDatabasePool() {
  if (!pool) {
    throw new Error('PostgreSQL database is not connected.')
  }

  return pool
}

// Initialize database tables
export async function initializeDatabase() {
  const db = getDatabasePool()

  await db.query(`
    
CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tran_id VARCHAR(100) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  account_number VARCHAR(64) NOT NULL,
  amount BIGINT NOT NULL CHECK (amount > 0),
  currency VARCHAR(3) NOT NULL DEFAULT 'KHR'
    CHECK (currency = 'KHR'),
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'CANCELLED')),
  payway_response_code TEXT,
  paid_at TIMESTAMPTZ,
  verification_evidence JSONB,
  status_access_token_hash VARCHAR(64)
    CHECK (
      status_access_token_hash IS NULL
      OR status_access_token_hash ~ '^[a-f0-9]{64}$'
    ),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

  `)

  await initializeAuthDatabase(db)

  console.info('PostgreSQL database schema initialized.')
}

// Check database readiness
export async function isDatabaseReady() {
  if (!pool) {
    return false
  }

  try {
    await pool.query('SELECT 1')
    return true
  } catch {
    return false
  }
}

// Disconnect PostgreSQL
export async function disconnectFromDatabase() {
  if (pool) {
    const currentPool = pool
    pool = null

    await currentPool.end()

    console.info('PostgreSQL disconnected.')
  }
}